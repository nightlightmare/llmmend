import { extractJson, type ExtractOptions } from 'llmmend/json'
import { block, h, json, pre, type Tool } from './dom'
import { jsonSchema } from './json-schema'

const samples: Record<string, string> = {
  fence:
    'Sure! Here is the weather data you asked for:\n\n```json\n{\n  "city": "Paris",\n  "temp": 21,\n  "conditions": ["sunny", "windy",],\n}\n```\n\nLet me know if you need anything else.',
  think:
    '<think>\nThe user wants a list. The format is {"items": [...]}, so two items should do.\n</think>\n\n{"items": [{"id": 1, "name": "apple"}, {"id": 2, "name": "pear"}]}',
  truncated:
    'Here are the results:\n{"results": [{"title": "First", "score": 0.92}, {"title": "Second", "score": 0.87}, {"title": "Thi',
  sloppy:
    "{\n  // generated by the model\n  name: 'llmmend',\n  stable: True,\n  latest: None,\n  tags: ['json', 'sse',],\n}",
}

/** One line per Issue: its code and where it happened. */
function describe(issue: Record<string, unknown>): string {
  const { code, ...rest } = issue
  const details = Object.entries(rest).map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
  return details.length ? `${String(code)} (${details.join(', ')})` : String(code)
}

export const tool: Tool = {
  samples,
  render(input, options, t) {
    type Options = Required<ExtractOptions<unknown>>
    const extract: ExtractOptions<unknown> = {
      pick: (options.pick ?? 'last') as Options['pick'],
      repair: (options.repair ?? 'full') as Options['repair'],
      expect: (options.expect ?? 'any') as Options['expect'],
    }
    const schemaText = options.schema?.trim()
    if (schemaText) {
      try {
        extract.schema = jsonSchema(JSON.parse(schemaText))
      } catch {
        return h('p', { class: 'error' }, t.json.schemaInvalid)
      }
    }
    const res = extractJson(input, extract)
    const issues = block(
      t.json.issues,
      res.issues.length
        ? h('ul', {}, ...res.issues.map((issue) => h('li', {}, h('code', {}, describe(issue)))))
        : h('p', {}, t.json.noIssues),
    )
    if (res.ok)
      return h(
        'div',
        {},
        h('p', { class: 'status ok' }, `✓ ${t.json.ok}`),
        block(t.json.value, json(res.value)),
        issues,
        block(t.json.raw, pre(res.raw)),
      )
    return h(
      'div',
      {},
      h('p', { class: 'status failed' }, `✗ ${t.json.failed}: `, h('code', {}, res.error)),
      res.error === 'schema_mismatch' &&
        block(
          t.json.schemaIssues,
          h(
            'ul',
            {},
            ...res.schemaIssues.map((issue) =>
              h(
                'li',
                {},
                issue.path?.length
                  ? `${issue.path.map((s) => String(typeof s === 'object' ? s.key : s)).join('.')}: `
                  : '',
                issue.message,
              ),
            ),
          ),
        ),
      res.error === 'schema_mismatch' && block(t.json.value, json(res.value)),
      issues,
    )
  },
}
